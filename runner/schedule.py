"""ASHA over ``n``: screen wide and cheap, spend resolution only on survivors.

Two constraints set this design, and both are measured.

**The evaluation is noisy.** To separate a ρ=0.25 candidate from a ρ=0.15 one
the gap is 0.074 and the noise is:

====== ====== ======
n      noise  usable
====== ====== ======
35     0.231  no
250    0.103  no
1,000  0.046  no
2,000  0.033  yes
====== ====== ======

So rung 1 (n=300) and rung 2 (n=1,000) buy **direction only**. No promotion
decision is made below rung 3, and :func:`promotable` refuses to hand one back.

**Rungs must nest.** An arm promoted from 300 to 1,000 should pay for 700 new
events, not 1,000. :func:`rung_events` therefore returns a deterministic prefix
of one fixed ordering, so every rung is a subset of the next and every arm is
scored on identical events at identical rungs — which is what keeps the
comparison paired and the quarter difficulty out of it.

That ordering puts the 2,100 events already generated by ``arms.py`` first, so
rungs 1–3 come out of cache for any arm that has run before and cost nothing to
re-score.

The promotion rule is ASHA's, not synchronous successive halving's: an arm is
promotable as soon as it ranks in the top ``1/η`` of the arms that have finished
its rung, whether or not the rest have. Nothing waits for a straggler.
"""

from __future__ import annotations

import hashlib
import json
import sys
from dataclasses import asdict, dataclass, field
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import harness  # noqa: E402
import reads  # noqa: E402

STATE = ROOT / "runs" / "schedule.json"

#: Total events per rung, summed across dev quarters. Rung 3 is the first that
#: can carry a promotion decision; anything below it is a screen.
RUNGS = (300, 1000, 2000)

#: The rung at or above which a promotion decision is allowed. Hard constraint 1
#: in BUILD_LOOP.md, enforced here rather than remembered.
SELECTION_RUNG = 2  # zero-indexed -> RUNGS[2] == 2000

#: Successive-halving reduction factor. Top 1/3 of each rung survives.
ETA = 3

#: Minimum arms finished at a rung before any promotion is allowed. Below this
#: "top 1/3 of what has finished" is one arm out of two, which is not a screen.
MIN_COHORT = 3

#: Metered spend ceiling, USD. OpenRouter/OpenAI only — Claude Code is on a Max
#: plan, so building and analysing is unmetered and only scoring runs count.
#: BUILD_LOOP.md: hold at 25 cumulative and ask before exceeding.
SPEND_CAP = 25.0

#: Spend that happened before this ledger existed, as of 2026-08-17.
SPEND_PRIOR = 11.81


# --------------------------------------------------------------------------
# The nested event ordering
# --------------------------------------------------------------------------


@lru_cache(maxsize=1)
def _ordering() -> tuple[tuple[str, str], ...]:
    """``(quarter, event_id)`` in the fixed order rungs are prefixes of.

    Three properties, each load-bearing:

    * **already-generated events first.** The 700-per-quarter screening sample
      ``arms.py`` used is put at the head, so a re-scored arm pays nothing for
      rungs 1–3.
    * **round-robin across quarters.** Any prefix is balanced, so rung 1 is not
      accidentally three-quarters of one quarter — which would make its
      difficulty, not the arm, the thing being measured.
    * **hashed within a quarter**, not sorted by ``event_id`` and strided.
      Striding a sorted list changes membership when the stride changes, and
      nesting is the property this ordering exists to provide.
    """
    screened = {e["event_id"] for e in reads.screen_events(reads.SCREEN_PER_QUARTER)}
    per_quarter: dict[str, list[str]] = {}
    for quarter in harness.DEV_QUARTERS:
        ids = [e["event_id"] for e in harness.events_for(quarter)]
        per_quarter[quarter] = sorted(
            ids,
            key=lambda i: (i not in screened, hashlib.sha256(i.encode()).hexdigest()),
        )
    order: list[tuple[str, str]] = []
    for i in range(max(len(v) for v in per_quarter.values())):
        for quarter in harness.DEV_QUARTERS:
            if i < len(per_quarter[quarter]):
                order.append((quarter, per_quarter[quarter][i]))
    return tuple(order)


def universe_size() -> int:
    return len(_ordering())


def rung_events(n: int | None = None) -> dict[str, list[dict]]:
    """The first ``n`` events of the fixed ordering, grouped by quarter.

    ``None`` means every dev event — the rung a final promotion decision runs
    on when a candidate has already earned it.
    """
    order = _ordering()
    take = order if n is None else order[:n]
    wanted: dict[str, set[str]] = {}
    for quarter, event_id in take:
        wanted.setdefault(quarter, set()).add(event_id)
    out: dict[str, list[dict]] = {}
    for quarter, ids in wanted.items():
        out[quarter] = [e for e in harness.events_for(quarter) if e["event_id"] in ids]
    return out


def rung_size(rung: int) -> int | None:
    return RUNGS[rung] if rung < len(RUNGS) else None


def confirmation_events() -> dict[str, list[dict]]:
    """Dev events **no rung ever touches** — the partition selection cannot see.

    This is the answer to the loop's own central problem, and it is the answer
    the post-selection-inference literature gives: to get an unbiased value for
    the best of ``K`` noisy candidates, select on one sample and estimate on
    another. Every other correction — deflated fitness, best-of-K multipliers,
    effective-``K`` adjustments — is an *estimate* of the bias under assumptions
    about independence and normality that our arms (mutually correlated at
    0.824) do not satisfy. A split needs no assumptions at all.

    It is nearly free here. The rungs occupy the first 2,000 events of a 6,144
    event ordering, so **4,144 dev events are already unused**, disjoint by
    construction, and cost nothing to score for any arm whose column is cached.

    Distinct from :data:`HOLDOUT` (2026Q3), which is sealed and spent once on
    the final model. This is the intermediate check the loop runs every
    generation: the gap between an arm's selection-set number and its
    confirmation number *is* the measured selection bias, rather than a
    formula's guess at it.
    """
    order = _ordering()
    tail = order[RUNGS[-1]:]
    wanted: dict[str, set[str]] = {}
    for quarter, event_id in tail:
        wanted.setdefault(quarter, set()).add(event_id)
    return {
        quarter: [e for e in harness.events_for(quarter) if e["event_id"] in ids]
        for quarter, ids in wanted.items()
    }


def new_events(arm_rung: int | None, target_rung: int) -> dict[str, list[dict]]:
    """Events at ``target_rung`` that were not already in ``arm_rung``.

    What :meth:`Arm.ensure` is asked to generate. Promotion pays the difference,
    not the total.
    """
    target = rung_events(rung_size(target_rung))
    if arm_rung is None:
        return target
    already = rung_events(rung_size(arm_rung))
    out = {}
    for quarter, events in target.items():
        seen = {e["event_id"] for e in already.get(quarter, [])}
        out[quarter] = [e for e in events if e["event_id"] not in seen]
    return out


# --------------------------------------------------------------------------
# Metered spend
