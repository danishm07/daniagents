#: Directories whose JSONL columns carry ``prompt_tokens`` / ``completion_tokens``.
SPEND_DIRS = ("arms", "reads", "frontier")


def _model_from_filename(path: Path) -> str:
    """``rulebook__google_gemini-2.5-flash-lite.jsonl`` -> the OpenRouter id."""
    stem = path.stem
    tail = stem.split("__")[-1]
    return tail.replace("_", "/", 1) if "_" in tail else tail


def spent_usd() -> float:
    """Everything the token ledgers on disk say we have spent, plus the prior.

    Reconstructed from the columns rather than tracked in a counter, because a
    counter drifts and the columns are the artefact that actually cost money.
    """
    import frontier

    total = 0.0
    for directory in SPEND_DIRS:
        for path in (ROOT / "data" / directory).glob("*.jsonl"):
            price_in, price_out = frontier.PRICES.get(_model_from_filename(path), (0.10, 0.40))
            tin = tout = 0
            for line in path.open():
                if not line.strip():
                    continue
                row = json.loads(line)
                tin += row.get("prompt_tokens") or 0
                tout += row.get("completion_tokens") or 0
            total += tin * price_in / 1e6 + tout * price_out / 1e6
    return total


def budget_remaining() -> float:
    return SPEND_CAP - max(spent_usd(), SPEND_PRIOR)


# --------------------------------------------------------------------------
# The schedule itself
# --------------------------------------------------------------------------


@dataclass
class State:
    """Which rung each arm has reached, and what it scored there.

    Persisted after every step. An interrupted loop resumes at the rung it
    reached — the LLM columns are on disk anyway, so a restart that forgot the
    schedule would re-score for free but re-decide from scratch.
    """

    rung: dict[str, int] = field(default_factory=dict)
    fitness: dict[str, dict[str, float]] = field(default_factory=dict)
    dropped: dict[str, str] = field(default_factory=dict)

    def save(self, path: Path = STATE) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(asdict(self), indent=2))

    @classmethod
    def load(cls, path: Path = STATE) -> State:
        if not path.exists():
            return cls()
        return cls(**json.loads(path.read_text()))

    def record(self, arm: str, rung: int, fitness: float, standalone: float) -> None:
        self.rung[arm] = rung
        self.fitness.setdefault(str(rung), {})[arm] = fitness
        self.fitness.setdefault(f"{rung}_standalone", {})[arm] = standalone

    def drop(self, arm: str, reason: str) -> None:
        self.dropped[arm] = reason


def promotable(
    state: State,
    arm: str,
    rung: int,
    *,
    holds_cell: bool = True,
    costed: bool = True,
) -> tuple[bool, str]:
    """Two gates, and they answer different questions.

    **Quality-diversity gate — does the arm still hold an archive cell?** This
    is the one that keeps the loop from converging on redundancy. Fifteen read
    columns all land in the same ``(ρ_b band, family, tier)`` cell, so at most
    one of them survives it however well they score standalone. That is the
    six-models-one-arm result made operational: a family cannot buy promotion
    slots with arm count.

    **Budget gate — is the arm in the top ``1/η`` of this rung's cohort?**
    Successive halving exists to allocate *spend*. An arm that costs nothing to
    take deeper consumes no budget, so applying the bar to it would discard
    information for free. Only costed arms face it.

    Returns ``(False, reason)`` rather than raising: a silent drop is how "we
    tried forty things" quietly becomes "we found one thing".
    """
    cohort = state.fitness.get(str(rung), {})
    if arm not in cohort:
        return False, f"not scored at rung {rung}"
    # Both gates exist to ration *spend*. A free arm consumes none, so dropping
    # it discards information for nothing — and at rung 0 the noise is 0.231
    # against candidate gaps of ~0.07, so a cell contest decided there is a coin
    # flip. Free arms ride to the decision rung and are judged where the
    # measurement can carry a judgement.
    if not costed:
        return True, "costs nothing to take deeper"
    if not holds_cell:
        return False, f"lost its archive cell at rung {rung} — a redundant duplicate of a better arm"
    if len(cohort) < MIN_COHORT:
        return False, f"only {len(cohort)} arms finished rung {rung}; need {MIN_COHORT}"
    ranked = sorted(cohort, key=lambda a: cohort[a], reverse=True)
    keep = max(1, len(ranked) // ETA)
    position = ranked.index(arm) + 1
    if position <= keep:
        return True, f"rank {position}/{len(ranked)} at rung {rung}, top {keep} promote"
    return False, f"rank {position}/{len(ranked)} at rung {rung}, only top {keep} promote"


def can_decide(rung: int) -> bool:
    """No promotion decision below n=2,000. Hard constraint 1."""
    return rung >= SELECTION_RUNG


if __name__ == "__main__":
    order = _ordering()
    print(f"universe {len(order)} dev events")
    for i, n in enumerate(RUNGS):
        events = rung_events(n)
        counts = {q: len(v) for q, v in sorted(events.items())}
        print(f"  rung {i}: n={n:<5} {counts}  decision-grade={can_decide(i)}")

    # Nesting is the property everything else rests on. Assert it rather than
    # trusting that a hash order stayed stable.
    small = {e["event_id"] for v in rung_events(RUNGS[0]).values() for e in v}
    big = {e["event_id"] for v in rung_events(RUNGS[-1]).values() for e in v}
    assert small <= big, "rungs must nest or promotion pays twice"
    print(f"\nrungs nest: {len(small)} in {len(big)}")

    screened = {e["event_id"] for e in reads.screen_events(reads.SCREEN_PER_QUARTER)}
    print(f"rung {RUNGS[-1]} inside the already-generated screening set: "
          f"{len(big & screened)}/{len(big)}")

    print(f"\nmetered spend so far ${spent_usd():.2f}  "
          f"(prior floor ${SPEND_PRIOR:.2f}, cap ${SPEND_CAP:.2f}, "
          f"remaining ${budget_remaining():.2f})")
